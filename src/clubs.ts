// Flat lookup. A key used in two leagues would silently collide, so this throws at load instead.
export const CLUB_COLORS: Record<string, [string, string]> = {};
for (const lg of Object.keys(CLUBS) as League[]) {
  for (const [k, v] of Object.entries(CLUBS[lg])) {
    if (CLUB_COLORS[k]) throw new Error('duplicate club key: ' + k);
    CLUB_COLORS[k] = v;
  }
}
